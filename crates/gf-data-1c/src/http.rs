//! Транспорт Streamable HTTP: тот же MCP, но по HTTP вместо stdio.
//!
//! # Зачем второй транспорт
//!
//! Stdio требует, чтобы клиент **запускал процесс сам**: конфигурация агента хранит путь
//! к бинарю и аргументы. Это верно для агента на той же машине, но не работает, когда
//! базы зарегистрированы на одной машине, а спрашивают с другой, и когда клиент один
//! процесс на сессию поднять не может (веб, контейнер, чужая песочница). Там нужен адрес,
//! а не команда.
//!
//! # Почему Streamable HTTP, а не SSE
//!
//! Транспорт HTTP+SSE из ревизии 2024-11-05 помечен устаревшим в 2025-03-26 — его заменил
//! Streamable HTTP: один адрес вместо двух, ответ телом обычного POST, а поток событий
//! только там, где он действительно нужен.
//!
//! # Что здесь НЕ сделано и почему
//!
//! **Потока `GET /mcp` нет** — на GET сервер отвечает 405, как разрешает спецификация тому,
//! кто не шлёт сообщений по своей воле. Слать ему нечего: уведомлений об изменении списка
//! инструментов он не делает (`listChanged: false`), прогресса не шлёт, вопросов клиенту
//! не задаёт.
//!
//! **Сессий (`Mcp-Session-Id`) нет.** Спецификация разрешает не заводить. Гейт построителя
//! при этом привязан к соединению: каждому запросу достаётся свой `Server`, и история
//! проверок текста запроса не течёт между клиентами.
//!
//! # Границы, названные прямо
//!
//! Сервер слушает `127.0.0.1`, пока не сказано иное, и проверяет заголовок `Origin`
//! (защита от DNS rebinding — требование спецификации к локальным HTTP-серверам). TLS нет;
//! аутентификация есть только та, что задана флагом `-token`, и она не изображает большего.
//!
//! Перенесено из `gyrfalcon` (наш продукт, MIT) с двумя добавлениями: проверка токена
//! и адрес `/health`, которых там нет.

use std::io::{BufRead, BufReader, Write};
use std::net::{TcpListener, TcpStream};
use std::time::Duration;

use serde_json::Value;

use crate::journal;
use crate::server::{Options, Server, VERSION};

/// Единственный адрес транспорта. Один — в этом и смысл Streamable HTTP.
const ПУТЬ: &str = "/mcp";

/// Адрес по умолчанию.
///
/// Локальный намеренно: сервер отдаёт данные информационных баз, и «слушать всё подряд»
/// должно быть осознанным решением.
pub const DEFAULT_ADDR: &str = "127.0.0.1:9077";

/// Предел размера тела запроса.
///
/// Вызов инструмента — это имя и десяток аргументов; мегабайты в нём означают не большой
/// вопрос, а испорченный или враждебный клиент. Читать объявленную длину на веру нельзя:
/// `Content-Length` пишет клиент.
const ПРЕДЕЛ_ТЕЛА: usize = 1 << 20;

/// Сколько ждать запроса в открытом соединении.
const ОЖИДАНИЕ: Duration = Duration::from_secs(30);

/// Разобранный HTTP-запрос — ровно те поля, на которые сервер смотрит.
struct Запрос {
    метод: String,
    путь: String,
    origin: Option<String>,
    authorization: Option<String>,
    тело: Vec<u8>,
    /// Объявленный размер тела, если он больше предела. Тело в этом случае не читается
    /// вовсе — иначе предел не защищал бы ни от чего.
    превышение: Option<usize>,
}

/// Ответ HTTP: код, тип, тело и то, что понадобилось сверх них.
struct Ответ {
    код: u16,
    причина: &'static str,
    тип: &'static str,
    заголовки: Vec<(&'static str, &'static str)>,
    тело: Vec<u8>,
}

impl Ответ {
    fn json(v: &Value) -> Self {
        Self {
            код: 200,
            причина: "OK",
            тип: "application/json; charset=utf-8",
            заголовки: Vec::new(),
            тело: serde_json::to_vec(v).unwrap_or_default(),
        }
    }

    /// 202 на сообщения, ответа не требующие (уведомления).
    ///
    /// Пустое 200 сказало бы клиенту «вот твой ответ, он пуст» — а ответа на уведомление
    /// не бывает вовсе, и 202 говорит именно это.
    fn принято() -> Self {
        Self {
            код: 202,
            причина: "Accepted",
            тип: "text/plain; charset=utf-8",
            заголовки: Vec::new(),
            тело: Vec::new(),
        }
    }

    fn текст(
        код: u16, причина: &'static str, текст: impl Into<String>
    ) -> Self {
        Self {
            код,
            причина,
            тип: "text/plain; charset=utf-8",
            заголовки: Vec::new(),
            тело: текст.into().into_bytes(),
        }
    }

    fn с_заголовком(
        mut self, имя: &'static str, значение: &'static str
    ) -> Self {
        self.заголовки.push((имя, значение));
        self
    }
}

/// Слушает ли сервер что-то, кроме собственной машины.
///
/// Проверяется по имени интерфейса, а не по числу возможных клиентов: даже `0.0.0.0`
/// в контейнере с одной сетью может быть безобиднее петли на общем хосте. Сервер не
/// берётся судить об окружении — он говорит, что видит.
fn не_только_свой(адрес: &str) -> bool {
    let хост = match адрес.rsplit_once(':') {
        Some((h, п)) if п.chars().all(|c| c.is_ascii_digit()) => h,
        _ => адрес,
    };
    !matches!(хост, "127.0.0.1" | "localhost" | "::1" | "[::1]")
}

/// Поднять транспорт и обслуживать, пока не прервут.
pub fn serve(options: Options, адрес: &str, токен: &str) -> Result<(), String> {
    let адрес = if адрес.trim().is_empty() {
        DEFAULT_ADDR
    } else {
        адрес.trim()
    };
    let listener =
        TcpListener::bind(адрес).map_err(|e| format!("адрес {адрес} не занят сервером: {e}"))?;
    let фактический = listener
        .local_addr()
        .map(|a| a.to_string())
        .unwrap_or_else(|_| адрес.to_string());

    // Здесь stdout не свят, в отличие от stdio-транспорта: по нему никто не читает
    // JSON-RPC, а человеку, запустившему сервер руками, адрес нужен в терминале.
    eprintln!("gf-data-1c {VERSION} слушает http://{фактический}{ПУТЬ}");
    if не_только_свой(&фактический) {
        // Предупреждение, а не отказ: в контейнере это и есть рабочий режим.
        eprintln!(
            "ВНИМАНИЕ: адрес не локальный — сервер отдаёт данные баз всем, кто до него \
             дотянется.{}",
            if токен.is_empty() {
                " Токен НЕ задан — поставьте -token."
            } else {
                " Токен задан."
            }
        );
    }
    journal::writef(format_args!("сетевой режим: слушаю {фактический}"));

    for поток in listener.incoming() {
        match поток {
            Ok(s) => {
                if let Err(e) = обслужить(s, &options, токен) {
                    eprintln!("запрос не обслужен: {e}");
                }
            }
            Err(e) => eprintln!("соединение не принято: {e}"),
        }
    }
    Ok(())
}

fn обслужить(
    mut s: TcpStream, options: &Options, токен: &str
) -> std::io::Result<()> {
    s.set_read_timeout(Some(ОЖИДАНИЕ))?;
    let mut r = BufReader::new(s.try_clone()?);
    let Some(з) = разобрать_запрос(&mut r)? else {
        return Ok(()); // соединение открыли и закрыли, не сказав ничего
    };
    // Сервер собирается на запрос: состояние (реестр, таймауты) общее, а гейт
    // построителя — свой, и течь между клиентами ему нечем.
    let mut сервер = Server::new(options.clone());
    let ответ = маршрут(&з, токен, |строка| сервер.handle(строка));
    отправить(&mut s, &ответ)
}

/// Прочитать одну строку заголовка — БАЙТАМИ, а не как UTF-8.
///
/// `read_line` на невалидном UTF-8 возвращает ошибку и обрывает соединение молча: клиент
/// видит пустой ответ и решает, что сервер сломался. А прислать такой байт может кто
/// угодно — заголовки по стандарту латинские, но `Authorization` с кириллическим токеном
/// или чужая кодировка в `User-Agent` встречаются живьём (поймано пробой 04.09.2026:
/// curl с токеном «тест» клал каждый запрос).
///
/// Портится при этом ровно то, что и так не разобрать; остальные заголовки читаются.
fn прочитать_строку<R: BufRead>(r: &mut R) -> std::io::Result<Option<String>> {
    let mut буфер = Vec::new();
    if r.read_until(b'\n', &mut буфер)? == 0 {
        return Ok(None);
    }
    Ok(Some(String::from_utf8_lossy(&буфер).into_owned()))
}

/// Прочитать запрос целиком. `None` — запроса не было (соединение закрылось).
fn разобрать_запрос<R: BufRead>(r: &mut R) -> std::io::Result<Option<Запрос>> {
    let Some(строка) = прочитать_строку(r)? else {
        return Ok(None);
    };
    let mut части = строка.split_whitespace();
    let метод = части.next().unwrap_or_default().to_ascii_uppercase();
    if метод.is_empty() {
        return Ok(None);
    }
    let путь = части.next().unwrap_or("/").to_string();

    let mut origin = None;
    let mut authorization = None;
    let mut длина: Option<usize> = None;
    let mut чанками = false;
    while let Some(h) = прочитать_строку(r)? {
        let h = h.trim_end_matches(['\r', '\n']);
        if h.is_empty() {
            break;
        }
        let Some((имя, значение)) = h.split_once(':') else {
            continue;
        };
        match имя.trim().to_ascii_lowercase().as_str() {
            "origin" => origin = Some(значение.trim().to_string()),
            "authorization" => authorization = Some(значение.trim().to_string()),
            "content-length" => длина = значение.trim().parse().ok(),
            "transfer-encoding" => чанками = значение.to_ascii_lowercase().contains("chunked"),
            // Mcp-Session-Id и MCP-Protocol-Version читать незачем: сессий сервер
            // не заводит, а версию протокола он уже согласовал в initialize.
            _ => {}
        }
    }

    let (тело, превышение) = if чанками {
        прочитать_кусками(r)?
    } else {
        match длина {
            Some(n) if n > ПРЕДЕЛ_ТЕЛА => (Vec::new(), Some(n)),
            Some(n) => {
                let mut b = vec![0u8; n];
                r.read_exact(&mut b)?;
                (b, None)
            }
            None => (Vec::new(), None),
        }
    };

    Ok(Some(Запрос {
        метод,
        путь,
        origin,
        authorization,
        тело,
        превышение,
    }))
}

/// Тело, разбитое на куски (`Transfer-Encoding: chunked`).
///
/// Клиент вправе не знать длину заранее — так делают HTTP-библиотеки, отдающие тело
/// потоком. Отказ на chunked выглядел бы у такого клиента как «сервер не работает».
fn прочитать_кусками<R: BufRead>(
    r: &mut R,
) -> std::io::Result<(Vec<u8>, Option<usize>)> {
    let mut тело = Vec::new();
    while let Some(заголовок) = прочитать_строку(r)? {
        // После размера бывают расширения через `;` — они нас не касаются.
        let размер_текст = заголовок.trim().split(';').next().unwrap_or("").trim();
        if размер_текст.is_empty() {
            continue;
        }
        let размер = usize::from_str_radix(размер_текст, 16).map_err(|_| {
            std::io::Error::new(
                std::io::ErrorKind::InvalidData,
                format!("не разобрал размер куска: {размер_текст}"),
            )
        })?;
        if размер == 0 {
            break; // трейлеры дочитывать незачем: соединение всё равно закрывается
        }
        if тело.len() + размер > ПРЕДЕЛ_ТЕЛА {
            return Ok((Vec::new(), Some(тело.len() + размер)));
        }
        let mut кусок = vec![0u8; размер];
        r.read_exact(&mut кусок)?;
        тело.extend_from_slice(&кусок);
        let mut хвост = [0u8; 2]; // CRLF после куска
        r.read_exact(&mut хвост)?;
    }
    Ok((тело, None))
}

/// Что сервер отвечает на разобранный запрос.
///
/// Обработка сообщений передана замыканием, а не взята из `Server` напрямую: так решения
/// транспорта (кого пустить, что за код вернуть) проверяются тестами без реестра баз
/// на диске и без открытого порта.
fn маршрут(
    з: &Запрос,
    токен: &str,
    mut обработать: impl FnMut(&str) -> Option<Value>,
) -> Ответ {
    // Защита от DNS rebinding: страница со стороннего домена может послать запрос на
    // localhost, и без этой проверки чужой сайт читал бы ДАННЫЕ ИНФОРМАЦИОННЫХ БАЗ руками
    // браузера. Требование спецификации, а не осторожность сверх неё.
    if let Some(откуда) = &з.origin {
        if !локальный_origin(откуда) {
            return Ответ::текст(
                403,
                "Forbidden",
                format!(
                    "origin {откуда} отклонён: сервер обслуживает только localhost. \
                     Это не настройка — у него нет TLS, и открывать его чужой странице \
                     нечем защитить"
                ),
            );
        }
    }

    let адрес = з.путь.split('?').next().unwrap_or("/");

    // Проба живости отвечает без токена: она нужна тому, кто разворачивает сервер,
    // и говорит только версию — ни данных, ни состава баз в ней нет.
    if адрес == "/health" {
        return Ответ::текст(200, "OK", format!("gf-data-1c {VERSION}\n"));
    }

    if адрес != ПУТЬ && адрес != "/" {
        return Ответ::текст(
            404,
            "Not Found",
            format!("нет такого адреса: {адрес}. MCP отвечает на {ПУТЬ}"),
        );
    }

    // Токен проверяется ПОСЛЕ origin и адреса: отказ в доступе не должен подтверждать
    // чужой странице, что по этому адресу вообще что-то есть.
    if !токен.is_empty() {
        let ждём = format!("Bearer {токен}");
        if з.authorization.as_deref() != Some(ждём.as_str()) {
            journal::writef(format_args!("сетевой режим: отказ в доступе"));
            return Ответ::текст(
                401,
                "Unauthorized",
                "нужен заголовок Authorization: Bearer <токен>",
            );
        }
    }

    match з.метод.as_str() {
        "POST" => {}
        "GET" => {
            return Ответ::текст(
                405,
                "Method Not Allowed",
                "поток событий сервер не открывает: слать по своей воле ему нечего \
                 (listChanged: false, прогресса и вопросов клиенту нет). \
                 Ответы приходят телом POST на тот же адрес",
            )
            .с_заголовком("Allow", "POST")
        }
        "DELETE" => {
            return Ответ::текст(
                405,
                "Method Not Allowed",
                "сессий сервер не заводит — закрывать нечего",
            )
            .с_заголовком("Allow", "POST")
        }
        другой => {
            return Ответ::текст(
                405,
                "Method Not Allowed",
                format!("метод {другой} не обслуживается: сообщения приходят POST на {ПУТЬ}"),
            )
            .с_заголовком("Allow", "POST")
        }
    }

    if let Some(объявлено) = з.превышение {
        return Ответ::текст(
            413,
            "Payload Too Large",
            format!(
                "тело {объявлено} байт при пределе {ПРЕДЕЛ_ТЕЛА}: вызов инструмента \
                 столько не весит"
            ),
        );
    }

    let текст = String::from_utf8_lossy(&з.тело).into_owned();
    match serde_json::from_str::<Value>(&текст) {
        // Пакет сообщений (JSON-RPC batch): в ревизии 2025-03-26 клиент вправе его
        // прислать. Ответ — массив только из тех, у кого был id.
        Ok(Value::Array(пакет)) => {
            let ответы: Vec<Value> = пакет
                .iter()
                .filter_map(|м| обработать(&м.to_string()))
                .collect();
            if ответы.is_empty() {
                Ответ::принято()
            } else {
                Ответ::json(&Value::Array(ответы))
            }
        }
        // Одно сообщение — и мусор тоже: на неразобранный JSON отвечает сам сервер своей
        // ошибкой протокола, чтобы конверт ошибки был один и тот же независимо
        // от транспорта.
        _ => match обработать(&текст) {
            Some(готовый) => Ответ::json(&готовый),
            None => Ответ::принято(),
        },
    }
}

/// Localhost ли в заголовке `Origin`.
///
/// Три имени, а не вся сеть 127.0.0.0/8: длинный список выглядел бы внимательным, но
/// каждая лишняя строка в нём — это адрес, по которому сервер согласится отвечать,
/// а проверить его некому.
fn локальный_origin(origin: &str) -> bool {
    let без_схемы = origin
        .split_once("://")
        .map(|(_, остаток)| остаток)
        .unwrap_or(origin);
    let хост = без_схемы.split('/').next().unwrap_or("");
    // Порт отрезаем; IPv6 приходит в скобках — `[::1]:9077`.
    let хост = match хост.rsplit_once(':') {
        Some((h, п)) if !п.is_empty() && п.chars().all(|c| c.is_ascii_digit()) => h,
        _ => хост,
    };
    let хост = хост.trim_start_matches('[').trim_end_matches(']');
    matches!(хост, "localhost" | "127.0.0.1" | "::1")
}

fn отправить<W: Write>(w: &mut W, ответ: &Ответ) -> std::io::Result<()> {
    let mut головa = format!(
        "HTTP/1.1 {} {}\r\nContent-Type: {}\r\nContent-Length: {}\r\nConnection: close\r\n",
        ответ.код,
        ответ.причина,
        ответ.тип,
        ответ.тело.len()
    );
    for (имя, значение) in &ответ.заголовки {
        головa.push_str(&format!("{имя}: {значение}\r\n"));
    }
    головa.push_str("\r\n");
    w.write_all(головa.as_bytes())?;
    w.write_all(&ответ.тело)?;
    w.flush()
}

