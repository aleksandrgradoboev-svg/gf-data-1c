    #[test]
    fn битый_байт_в_заголовке_не_роняет_запрос() {
        // read_line на невалидном UTF-8 возвращает ошибку, и соединение обрывается молча:
        // клиент видит пустой ответ и решает, что сервер сломался. Поймано живой пробой
        // 04.09.2026 — curl из cp1251-оболочки шлёт кириллический токен не в UTF-8,
        // и КАЖДЫЙ такой запрос падал ещё до маршрута.
        //
        // Прислать негодный байт может кто угодно: заголовки по стандарту латинские, но
        // это правило соблюдают не все. Битое портится, остальное читается.
        let mut сырьё: Vec<u8> = b"POST /mcp HTTP/1.1\r\nAuthorization: Bearer ".to_vec();
        сырьё.extend_from_slice(&[0xF2, 0xE5, 0xF1, 0xF2]); // «тест» в cp1251
        сырьё.extend_from_slice(b"\r\nContent-Length: 40\r\n\r\n");
        сырьё.extend_from_slice(br#"{"jsonrpc":"2.0","id":1,"method":"ping"}"#);

        let mut r = std::io::BufReader::new(&сырьё[..]);
        let з = разобрать_запрос(&mut r)
            .expect("разбор обязан пережить негодный байт")
            .expect("запрос обязан быть");
        assert_eq!(з.метод, "POST");
        assert_eq!(з.путь, "/mcp");
        assert!(
            з.authorization.is_some(),
            "заголовок прочитан, пусть и с потерями"
        );
        // Тело за битым заголовком читается целиком — иначе потеря была бы не только
        // в кодировке.
        assert_eq!(з.тело.len(), 40);
    }
