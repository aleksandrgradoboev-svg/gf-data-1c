//! Гейт построителя запросов: механизм вместо правила.
//!
//! `query` выполняет ТОЛЬКО текст, который в этой же сессии собрал `query_build`
//! (решение 27.08.2026: «завернуть всё на построитель»). Текст, написанный руками,
//! не выполняется даже после удачного `query_check` — тот остаётся диагностикой
//! синтаксиса, не пропуском. Соединения и пакеты построитель не собирает, и такой
//! вопрос честно возвращается как «не собирается» — это принятая цена.
//!
//! Вторая половина: после отказа `query_check` следующий текст не разбирается, пока
//! не позван построитель.
//!
//! Зачем механизм, а не строка в промпте: правило «три отказа — остановись» стояло
//! в агенте, и прогон 27.08.2026 (qwen3.6, Kilo) дал 21 отказ `query_check` подряд
//! при одном вызове построителя — с ключом на китайском. Промпт читают, а не
//! исполняют; сервер исполняет.
//!
//! Состояние живёт в сессии, а не в процессе. В stdio сессия одна и совпадает с
//! процессом; в сетевом режиме сервер собирается на каждую новую сессию, поэтому у
//! каждого подключения свой гейт, и одобренный текст не течёт между клиентами.

use std::collections::HashSet;
use std::sync::Mutex;

/// Состояние гейта одной сессии.
#[derive(Default)]
pub struct QueryGate {
    inner: Mutex<Inner>,
}

#[derive(Default)]
struct Inner {
    /// Нормализованные тексты, одобренные к выполнению.
    approved: HashSet<String>,
    /// Закрыта ли проверка текста после отказа `query_check`.
    check_locked: bool,
    /// Первая таблица после «ИЗ» отказанного текста — для примера в подсказке.
    last_source: String,
}

impl QueryGate {
    pub fn new() -> Self {
        Self::default()
    }

    fn lock(&self) -> std::sync::MutexGuard<'_, Inner> {
        self.inner.lock().unwrap_or_else(|e| e.into_inner())
    }

    /// Запоминает текст как собранный платформой.
    pub fn approve(&self, text: &str) {
        self.lock().approved.insert(normalize_query(text));
    }

    /// Можно ли выполнять этот текст.
    pub fn is_approved(&self, text: &str) -> bool {
        self.lock().approved.contains(&normalize_query(text))
    }

    /// Закрывает проверку текста до вызова построителя.
    pub fn on_check_refused(&self, text: &str) {
        let mut g = self.lock();
        g.check_locked = true;
        g.last_source = source_of(text);
    }

    /// Текст разобран: замок снят. К выполнению это текст НЕ открывает.
    pub fn on_check_passed(&self) {
        self.lock().check_locked = false;
    }

    /// Построитель позван; исход неважен, проверка текста снова открыта.
    ///
    /// Именно любой исход: соединения и пакеты построитель не собирает, и без этой
    /// оговорки такой запрос встал бы намертво.
    pub fn on_build_called(&self) {
        self.lock().check_locked = false;
    }

    /// Открыта ли проверка текста. Если нет — второе значение объясняет, куда идти.
    pub fn check_allowed(&self) -> (bool, String) {
        let g = self.lock();
        if !g.check_locked {
            (true, String::new())
        } else {
            (false, builder_hint(&g.last_source))
        }
    }
}

/// Готовый вызов построителя под источник отказанного текста.
///
/// Пример конкретный, а не «воспользуйтесь query_build»: модель копирует форму,
/// а не читает совет.
fn builder_hint(source: &str) -> String {
    let source = if source.is_empty() {
        "Документ.ИмяДокумента"
    } else {
        source
    };
    format!(
        "после отказа проверки следующий текст не разбирается — соберите запрос построителем \
         query_build (текст пишет платформа, выдуманное поле отвергается поимённо), например: \
         {{\"base\": \"…\", \"источник\": \"{source}\", \"поля\": [\"Ссылка\", \
         {{\"поле\": \"СуммаДокумента\", \"функция\": \"СУММА\", \"как\": \"Сумма\"}}], \
         \"отбор\": [\"Дата МЕЖДУ &Н И &К\"], \"группировка\": [\"Ссылка\"]}}. \
         Собранный текст выполняйте query как есть. Соединения и пакеты построитель не собирает — \
         после его вызова проверка текста открывается снова"
    )
}

/// Текст сравнивается без учёта пробелов, переносов и регистра: платформа отдаёт
/// собранный текст с табуляцией, модель переписывает его в одну строку.
pub fn normalize_query(q: &str) -> String {
    q.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .to_uppercase()
}

/// Первая таблица после «ИЗ» — для примера вызова построителя, не для разбора.
pub fn source_of(q: &str) -> String {
    let upper = q.to_uppercase();
    let mut rest = upper.as_str();
    let mut offset = 0usize;

    while let Some(pos) = rest.find("ИЗ") {
        let abs = offset + pos;
        let before_ok = abs == 0
            || upper[..abs]
                .chars()
                .next_back()
                .is_some_and(char::is_whitespace);
        let after = &upper[abs + "ИЗ".len()..];
        let after_ok = after.chars().next().is_some_and(char::is_whitespace);

        if before_ok && after_ok {
            // Имя берётся из ИСХОДНОГО текста, а не из поднятого в верхний регистр:
            // «Документ.РеализацияТоваровУслуг» в подсказке должно выглядеть как в
            // запросе, иначе пример не скопируешь.
            let start = abs + "ИЗ".len();
            let tail = &q[start..];
            let name: String = tail
                .chars()
                .skip_while(|c| c.is_whitespace())
                .take_while(|c| c.is_alphanumeric() || *c == '_' || *c == '.')
                .collect();
            return name.trim_end_matches('.').to_string();
        }
        offset = abs + "ИЗ".len();
        rest = &upper[offset..];
    }
    String::new()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn выполняется_только_одобренный_текст() {
        let g = QueryGate::new();
        let текст = "ВЫБРАТЬ Ссылка ИЗ Справочник.Номенклатура";
        assert!(!g.is_approved(текст), "рукописный текст не выполняется");
        g.approve(текст);
        assert!(g.is_approved(текст));
    }

    #[test]
    fn пробелы_и_регистр_не_мешают_узнать_текст() {
        let g = QueryGate::new();
        g.approve("ВЫБРАТЬ\n\tСсылка\nИЗ\tСправочник.Номенклатура");
        assert!(
            g.is_approved("выбрать Ссылка из Справочник.Номенклатура"),
            "платформа отдаёт текст с табуляцией, модель переписывает в строку"
        );
    }

    #[test]
    fn после_одного_отказа_проверка_запирается() {
        let g = QueryGate::new();
        assert!(g.check_allowed().0);
        g.on_check_refused("ВЫБРАТЬ Чушь ИЗ Справочник.Номенклатура");
        let (можно, подсказка) = g.check_allowed();
        assert!(!можно, "порог — ОДИН отказ, а не три");
        assert!(подсказка.contains("query_build"), "{подсказка}");
        assert!(
            подсказка.contains("Справочник.Номенклатура"),
            "пример строится под источник отказанного текста: {подсказка}"
        );
    }

    #[test]
    fn вызов_построителя_открывает_проверку_при_любом_исходе() {
        let g = QueryGate::new();
        g.on_check_refused("ВЫБРАТЬ Чушь ИЗ Справочник.Номенклатура");
        assert!(!g.check_allowed().0);
        g.on_build_called();
        assert!(
            g.check_allowed().0,
            "иначе запрос с соединением встал бы намертво: построитель их не собирает"
        );
    }

    #[test]
    fn удачная_проверка_не_открывает_текст_к_выполнению() {
        let g = QueryGate::new();
        let текст = "ВЫБРАТЬ Ссылка ИЗ Справочник.Номенклатура";
        g.on_check_passed();
        assert!(
            !g.is_approved(текст),
            "разбор — диагностика синтаксиса, а не пропуск"
        );
    }

    #[test]
    fn источник_берётся_из_первой_таблицы_после_из() {
        assert_eq!(
            source_of("ВЫБРАТЬ Ссылка ИЗ Документ.РеализацияТоваровУслуг КАК Р"),
            "Документ.РеализацияТоваровУслуг"
        );
    }

    #[test]
    fn источник_сохраняет_исходный_регистр_имени() {
        let s = source_of("выбрать * из Справочник.Номенклатура");
        assert_eq!(
            s, "Справочник.Номенклатура",
            "пример должен копироваться как есть"
        );
    }

    #[test]
    fn без_из_источник_пуст() {
        assert!(source_of("ВЫБРАТЬ 1").is_empty());
    }

    #[test]
    fn из_внутри_слова_не_считается() {
        assert!(
            source_of("ВЫБРАТЬ РазмерИзделия").is_empty(),
            "«Из» в середине слова — не ключевое слово"
        );
    }
}
