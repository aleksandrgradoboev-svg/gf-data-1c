//! Гейт: разбор источника и нормализация — сверка с Go.
use gf_data_1c::tools::gate::{normalize_query, source_of};

fn main() {
    let тексты = [
        "ВЫБРАТЬ Ссылка ИЗ Документ.РеализацияТоваровУслуг КАК Р",
        "выбрать * из Справочник.Номенклатура",
        "ВЫБРАТЬ 1",
        "ВЫБРАТЬ РазмерИзделия",
        "ВЫБРАТЬ Ссылка\n\tИЗ\tРегистрНакопления.ТоварыНаСкладах.Остатки(&Дата)",
        "ВЫБРАТЬ А.Ссылка ИЗ Документ.Раз КАК А ЛЕВОЕ СОЕДИНЕНИЕ Документ.Два КАК Б ПО А.Ссылка = Б.Ссылка",
        "ИЗ Справочник.Первый",
        "выбратьизчего-то",
    ];
    for q in тексты {
        println!("source_of({q:?}) = {:?}", source_of(q));
    }
    println!("---");
    for q in [
        "ВЫБРАТЬ\n\tСсылка\nИЗ\tСправочник.Номенклатура",
        "выбрать Ссылка из Справочник.Номенклатура",
        "  ВЫБРАТЬ   1  ",
    ] {
        println!("normalize({q:?}) = {:?}", normalize_query(q));
    }
}
