/// Вопросы про типы платформы (`members: true`).
const ВОПРОСЫ_ЧЛЕНОВ: &[&str] = &[
    "ТаблицаЗначений",
    "ValueTable",
    "Запрос",
    "ТабличныйДокумент",
    "СхемаЗапроса",
    "Массив",
    "НетТакогоТипа",
    "Табл",
];

fn печать(s: &Set, q: &str, members: bool, full: bool) {
    let mut режим = String::new();
    if members {
        режим.push_str(" [members]");
    }
    if full {
        режим.push_str(" [full]");
    }
    println!("=== {q}{режим} ===");
    match s.syntax(&SyntaxInput {
        query: q.to_string(),
        members,
        full,
    }) {
        Ok(t) => println!("{t}"),
        Err(e) => println!("{e}"),
    }
}

fn main() {
    let s = Set::new(gf_data_1c::server::VERSION);
    for q in ВОПРОСЫ_СПРАВКИ {
        печать(&s, q, false, false);
    }
    for q in ВОПРОСЫ_ЧЛЕНОВ {
        печать(&s, q, true, false);
    }
    // Полная страница — отдельно: excerpt режет тело, и его границы тоже сверяются.
    печать(&s, "ПОДОБНО", false, true);
    println!("{} конец эталона", "─".repeat(20));
}
