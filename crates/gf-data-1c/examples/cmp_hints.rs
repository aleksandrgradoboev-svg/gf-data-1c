//! Обогащение отказов и тихие ловушки — сверка с Go на девяти случаях.
use gf_data_1c::refusal::{Kind, Refusal};
use gf_data_1c::tools::queryhints::{enrich_query_refusal, quiet_traps};
use std::collections::BTreeMap;

fn main() {
    let случаи: [(&str, &str); 9] = [
        (
            r#"Поле не найдено "Регистратор""#,
            "ВЫБРАТЬ Регистратор ИЗ РегистрБухгалтерии.Хозрасчетный.Обороты(&Н, &К)",
        ),
        (
            r#"Поле не найдено "ВНаличии""#,
            "ВЫБРАТЬ ВНаличии ИЗ РегистрНакопления.ТоварыНаСкладах.Остатки(&Дата)",
        ),
        (
            r#"Поле не найдено "СчетДт""#,
            "ВЫБРАТЬ СчетДт ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(&Н, &К)",
        ),
        (
            r#"Таблица не найдена "Справочник.ПланСчетов.Хозрасчетный""#,
            "ВЫБРАТЬ Ссылка ИЗ Справочник.ПланСчетов.Хозрасчетный",
        ),
        (
            r#"Неверные параметры "ОстаткиИОбороты, 3""#,
            "ВЫБРАТЬ * ИЗ РегистрБухгалтерии.Хозрасчетный.ОстаткиИОбороты(&Н, &К, , , , , )",
        ),
        (
            r#"Неверные параметры "ПОДОБНО""#,
            r#"ВЫБРАТЬ Ссылка ИЗ ПланСчетов.Хозрасчетный ГДЕ ПРЕДСТАВЛЕНИЕ ПОДОБНО "96%""#,
        ),
        (
            r#"Синтаксическая ошибка "НАЧАТОС""#,
            r#"ВЫБРАТЬ Ссылка ИЗ ПланСчетов.Хозрасчетный ГДЕ Код НАЧАТОС "96""#,
        ),
        (
            r#"Не задано значение параметра "Дата""#,
            "ВЫБРАТЬ * ИЗ РегистрНакопления.Товары.Остатки(&Дата)",
        ),
        (
            "Сравнение полей неограниченной длины",
            r#"ВЫБРАТЬ * ИЗ Документ.Реализация ГДЕ Контрагент.Ссылка = "Вася""#,
        ),
    ];
    let пусто: BTreeMap<String, String> = BTreeMap::new();
    for (i, (why, query)) in случаи.iter().enumerate() {
        let e = Refusal::new(Kind::BaseError, "запрос не выполнен", *why);
        println!("--- случай {} ---", i + 1);
        println!("{}", enrich_query_refusal(e, query, &пусто));
    }
    println!("=== тихие ловушки ===");
    let для = [
        r#"ВЫБРАТЬ * ИЗ Документ.Реализация ГДЕ Контрагент.Ссылка = "Вася""#,
        "ВЫБРАТЬ * ИЗ РегистрНакопления.Товары.Остатки(ДАТАВРЕМЯ(2026, 1, 31))",
        "ВЫБРАТЬ Ссылка ИЗ Справочник.Номенклатура",
    ];
    for (i, q) in для.iter().enumerate() {
        println!("ловушки {}: {}", i + 1, quiet_traps(q).join(" | "));
    }
}
