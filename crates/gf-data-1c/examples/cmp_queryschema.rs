//! Построитель и разбор запросов на живой базе — сверка с Go.
//!
//! Порядок и состав вызовов повторяют Go-пробник дословно: вывод обеих сторон
//! сравнивается `diff`, и расхождение в один пробел — уже расхождение.
use gf_data_1c::refusal::Refusal;
use gf_data_1c::tools::queryschema::*;
use gf_data_1c::tools::Set;

fn вывод(r: Result<String, Refusal>) {
    match r {
        Ok(t) => println!("{t}"),
        Err(e) => println!("{e}"),
    }
}

/// Разбирает вход ровно так, как это делает MCP-слой, и зовёт обработчик.
fn build(s: &Set, raw: &str) {
    match serde_json::from_str::<QueryBuildInput>(raw) {
        Ok(in_) => вывод(s.query_build(&in_)),
        Err(e) => println!("разбор ввода: {e}"),
    }
}

fn parse(s: &Set, query: &str) {
    вывод(s.query_parse(&QueryParseInput {
        base: "bu3".into(),
        query: query.into(),
    }));
}

fn main() {
    let s = Set::new(gf_data_1c::server::VERSION);

    println!("=== build: простая выборка ===");
    build(
        &s,
        r#"{"base":"bu3","from":"Справочник.Валюты","select":["Ссылка","Наименование"]}"#,
    );

    println!("=== build: агрегат с группировкой ===");
    build(
        &s,
        r#"{"base":"bu3","from":"Документ.СписаниеСРасчетногоСчета","alias":"Док",
        "select":[{"expr":"НАЧАЛОПЕРИОДА(Док.Дата, МЕСЯЦ)","as":"Месяц"},
                  {"field":"СуммаДокумента","func":"СУММА","as":"Сумма"}],
        "group_by":["Месяц"],"order_by":["Месяц"]}"#,
    );

    println!("=== build: русские ключи и строка вместо списка ===");
    build(
        &s,
        r#"{"base":"bu3","источник":"Справочник.Контрагенты","поля":["Ссылка"],
        "отбор":"ПометкаУдаления","первые":5}"#,
    );

    println!("=== build: стрингифицированный select ===");
    build(
        &s,
        r#"{"base":"bu3","from":"Справочник.Валюты","select":"[\"Ссылка\",\"Код\"]"}"#,
    );

    println!("=== build: параметр-счёт ===");
    build(
        &s,
        r#"{"base":"bu3","from":"РегистрБухгалтерии.Хозрасчетный.Обороты",
        "table_params":["&Н","&К","Месяц","Счет В ИЕРАРХИИ(&Счет)"],
        "select":["Счет","Период","СуммаОборотДт"],
        "params":[{"name":"Счет","account":"51"}]}"#,
    );

    println!("=== build: спор отбора с параметром таблицы ===");
    build(
        &s,
        r#"{"base":"bu3","from":"РегистрБухгалтерии.Хозрасчетный.Обороты",
        "table_params":["&Н","&К","Месяц","Счет В ИЕРАРХИИ(&Счет)"],
        "select":["Счет"],"where":["Счет = &Счет"]}"#,
    );

    println!("=== build: несуществующее поле ===");
    build(
        &s,
        r#"{"base":"bu3","from":"Справочник.Валюты","select":["НетТакогоПоля"]}"#,
    );

    println!("=== build: несуществующая таблица ===");
    build(
        &s,
        r#"{"base":"bu3","from":"Справочник.НетТакого","select":["Ссылка"]}"#,
    );

    println!("=== build: источник не назван ===");
    build(&s, r#"{"base":"bu3","select":["Ссылка"]}"#);

    println!("=== build: поля не заданы ===");
    build(&s, r#"{"base":"bu3","from":"Справочник.Валюты"}"#);

    println!("=== build: неизвестная база ===");
    build(
        &s,
        r#"{"base":"нетбазы","from":"Справочник.Валюты","select":["Ссылка"]}"#,
    );

    println!("=== parse: простой запрос ===");
    parse(
        &s,
        "ВЫБРАТЬ Ссылка, Наименование ИЗ Справочник.Валюты ГДЕ Код = &Код",
    );

    println!("=== parse: пакет с временной таблицей ===");
    parse(
        &s,
        "ВЫБРАТЬ Ссылка КАК В ПОМЕСТИТЬ ВТ ИЗ Справочник.Валюты;\nВЫБРАТЬ В ИЗ ВТ",
    );

    println!("=== parse: битый текст ===");
    parse(&s, "ВЫБРАТЬ ИЗ ГДЕ");

    println!("=== parse: пустой текст ===");
    parse(&s, "   ");
}
