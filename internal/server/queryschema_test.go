// Разбор и сборка запроса через СхемаЗапроса. Оба инструмента работают платформой
// живой базы, поэтому проверяются только живым прогоном — мока схемы не существует.

func TestLiveРазборЗапросаВСтруктуру(t *testing.T) {
	cs, ctx := liveSession(t)

	// Пакет с временной таблицей, виртуальной таблицей и вложенным запросом — тот
	// класс запросов, ради которого разбор и заведён. Простыню видно и глазами.
	запрос := `ВЫБРАТЬ Н.Ссылка КАК Ном
ПОМЕСТИТЬ ВТНоменклатура
ИЗ Справочник.Номенклатура КАК Н
ГДЕ НЕ Н.ПометкаУдаления
;
ВЫБРАТЬ Ост.Номенклатура КАК Номенклатура, Ост.ВНаличииОстаток КАК Остаток
ИЗ РегистрНакопления.ТоварыНаСкладах.Остатки(&НаДату, ) КАК Ост
	ВНУТРЕННЕЕ СОЕДИНЕНИЕ ВТНоменклатура КАК Т
	ПО Ост.Номенклатура = Т.Ном
УПОРЯДОЧИТЬ ПО Остаток УБЫВ
;
УНИЧТОЖИТЬ ВТНоменклатура`

	out, isErr := call(t, cs, ctx, "query_parse", map[string]any{
		"base": "ut11", "query": запрос,
	})
	if isErr {
		t.Fatalf("разбор пакета не прошёл: %s", out)
	}

	// Не «что-то вернулось», а состав: каждая строка ниже — отдельное обещание разбора.
	for _, ожидание := range []string{
		"запросов в пакете 3",
		"РегистрНакопления.ТоварыНаСкладах.Остатки",
		"Справочник.Номенклатура",
		"ВТНоменклатура",
		"НаДату",
		"уничтожение",
		"временнаяТаблица",
		"&НаДату",
		"Внутреннее",
	} {
		if !strings.Contains(out, ожидание) {
			t.Errorf("в разборе нет «%s»:\n%s", ожидание, out)
		}
	}
}

func TestLiveРазборОтвергаетВыдуманноеПоле(t *testing.T) {
	cs, ctx := liveSession(t)

	// Инструмент, отвечающий «разобрано» на то, чего нет, не разбирал ничего.
	out, _ := call(t, cs, ctx, "query_parse", map[string]any{
		"base":  "ut11",
		"query": "ВЫБРАТЬ Н.ТакогоПоляНетСовсем ИЗ Справочник.Номенклатура КАК Н",
	})
	if !strings.Contains(out, "ТакогоПоляНетСовсем") {
		t.Fatalf("отказ не назвал выдуманное поле:\n%s", out)
	}
}

func TestLiveСборкаЗапросаИзСтруктуры(t *testing.T) {
	cs, ctx := liveSession(t)

	out, isErr := call(t, cs, ctx, "query_build", map[string]any{
		"base":      "ut11",
		"источник":  "Документ.РеализацияТоваровУслуг.Товары",
		"псевдоним": "Тов",
		"поля": []any{
			map[string]any{"поле": "Номенклатура"},
			map[string]any{"функция": "СУММА", "поле": "Количество", "как": "Кол"},
		},
		"отбор":       []string{"Ссылка.Проведен", "Ссылка.Дата МЕЖДУ &Начало И &Конец"},
		"группировка": []string{"Номенклатура"},
		"порядок":     []string{"Кол"},
		"первые":      10,
	})
	if isErr {
		t.Fatalf("сборка не прошла: %s", out)
	}

	for _, ожидание := range []string{
		"ВЫБРАТЬ ПЕРВЫЕ 10",
		"СУММА(Тов.Количество) КАК Кол",
		"СГРУППИРОВАТЬ ПО",
		"УПОРЯДОЧИТЬ ПО",
		"Тов.Ссылка.Проведен",
		"Начало",
		"Конец",
	} {
		if !strings.Contains(out, ожидание) {
			t.Errorf("в собранном запросе нет «%s»:\n%s", ожидание, out)
		}
	}

	// Круг: собранный текст обязан проходить проверку платформой.
	проверка, isErr := call(t, cs, ctx, "query_check", map[string]any{
		"base": "ut11", "query": textOfBuiltQuery(out),
	})
	if isErr {
		t.Fatalf("собранный запрос не прошёл query_check: %s", проверка)
	}
}

func TestLiveСборкаВиртуальнойТаблицы(t *testing.T) {
	cs, ctx := liveSession(t)

	out, isErr := call(t, cs, ctx, "query_build", map[string]any{
		"base":             "ut11",
		"источник":         "РегистрНакопления.ТоварыНаСкладах.Остатки",
		"псевдоним":        "Ост",
		"параметрыТаблицы": []string{"&НаДату", "Склад = &Склад"},
		"поля": []any{
			map[string]any{"поле": "Номенклатура"},
			map[string]any{"поле": "ВНаличииОстаток", "как": "Остаток"},
		},
	})
	if isErr {
		t.Fatalf("сборка по виртуальной таблице не прошла: %s", out)
	}
	if !strings.Contains(out, "Остатки(&НаДату, Склад = &Склад)") {
		t.Errorf("параметры виртуальной таблицы не попали в текст:\n%s", out)
	}
}

func TestLiveСборкаОтвергаетВыдуманное(t *testing.T) {
	cs, ctx := liveSession(t)

	// Выдуманная таблица.
	out, _ := call(t, cs, ctx, "query_build", map[string]any{
		"base": "ut11", "источник": "Справочник.ТакойТаблицыНет",
		"поля": []any{map[string]any{"поле": "Наименование"}},
	})
	if !strings.Contains(out, "ТакойТаблицыНет") {
		t.Errorf("отказ не назвал выдуманную таблицу:\n%s", out)
	}

	// Выдуманное поле — ловится платформой при добавлении, с именем виновного.
	out, _ = call(t, cs, ctx, "query_build", map[string]any{
		"base": "ut11", "источник": "Справочник.Номенклатура",
		"поля": []any{map[string]any{"поле": "ТакогоПоляНетСовсем"}},
	})
	if !strings.Contains(out, "ТакогоПоляНетСовсем") {
		t.Errorf("отказ не назвал выдуманное поле:\n%s", out)
	}

	// Лишний параметр виртуальной таблицы — отказ со счётом позиций.
	out, _ = call(t, cs, ctx, "query_build", map[string]any{
		"base": "ut11", "источник": "РегистрНакопления.ТоварыНаСкладах.Остатки",
		"параметрыТаблицы": []string{"&А", "&Б", "&Лишний"},
		"поля":             []any{map[string]any{"поле": "Номенклатура"}},
	})
	if !strings.Contains(out, "принимает параметров") {
		t.Errorf("лишний параметр не отвергнут со счётом:\n%s", out)
	}
}

// textOfBuiltQuery вырезает сам запрос из ответа query_build: текст стоит между
// заголовком и хвостом с параметрами.
func textOfBuiltQuery(out string) string {
	s := out
	if i := strings.Index(s, ":\n\n"); i >= 0 {
		s = s[i+3:]
	}
	if i := strings.Index(s, "\n\nПараметры"); i >= 0 {
		s = s[:i]
	}
	if i := strings.Index(s, "\n\nВыполнить"); i >= 0 {
		s = s[:i]
	}
	return s
}
