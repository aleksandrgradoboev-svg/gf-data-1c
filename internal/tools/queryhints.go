var (
	reFieldNotFound = regexp.MustCompile(`Поле не найдено "([^"]+)"`)
	reTableNotFound = regexp.MustCompile(`Таблица не найдена "([^"]+)"`)
	reBadParams     = regexp.MustCompile(`Неверные параметры "([^",]+)(?:, ?(\d+))?"`)
	reNoParamValue  = regexp.MustCompile(`Не задано значение параметра "([^"]+)"`)
	reSyntax        = regexp.MustCompile(`Синтаксическая ошибка "([^"]+)"`)
	reVirtualUse    = regexp.MustCompile(`(?i)\.(ОстаткиИОбороты|ОстаткиИОборотыДтКт|Остатки|ОборотыДтКт|Обороты|ДвиженияССубконто|СрезПоследних|СрезПервых)\s*\(`)
	// Вид регистра вместе с виртуальной таблицей: имена «Остатки», «Обороты» и
	// «ОстаткиИОбороты» одинаковы у регистра накопления и регистра бухгалтерии, а состав
	// полей у них разный. Без вида подсказка отвечала бухгалтерскими Счет и Субконто на
	// вопрос про товарный регистр — то есть уверенно называла поля, которых там нет.
	reRegisterKind = regexp.MustCompile(`(?i)(РегистрНакопления|РегистрБухгалтерии|РегистрСведений|РегистрРасчета)\.[A-Za-zА-Яа-яЁё0-9_]+\.(ОстаткиИОбороты|ОстаткиИОборотыДтКт|Остатки|ОборотыДтКт|Обороты|ДвиженияССубконто|СрезПоследних|СрезПервых)\s*\(`)
)

// virtualTableIn — какая виртуальная таблица упомянута в тексте запроса. Ошибка платформы
// про поле не называет таблицу, а вызывающему нужно знать, где именно поля нет.
func virtualTableIn(query string) string {
	m := reVirtualUse.FindStringSubmatch(query)
	if m == nil {
		return ""
	}
	name := m[1]
	for k := range virtualTableFields {
		if strings.EqualFold(k, name) {
			return k
		}
	}
	return name
}

// registerKindIn — вид регистра, у которого спрашивали виртуальную таблицу.
func registerKindIn(query string) string {
	if m := reRegisterKind.FindStringSubmatch(query); m != nil {
		return strings.ToLower(m[1])
	}
	return ""
}

// nonAccountingFields — состав виртуальных таблиц НЕбухгалтерских регистров. Конкретные имена
// здесь назвать нельзя: измерения и ресурсы у каждого регистра свои, а ресурс в виртуальной
// таблице переименовывается (ВНаличии → ВНаличииОстаток). Поэтому подсказка описывает ПРАВИЛО
// и отправляет за именами к object — выдуманное имя выглядит убедительнее правила и стоит
// вызывающему второй ошибки.
var nonAccountingFields = map[string]string{
	"остатки":         "измерения регистра + ресурсы с суффиксом «Остаток» (ВНаличии → ВНаличииОстаток). Регистратора и Периода в ней нет",
	"обороты":         "измерения регистра + ресурсы с суффиксом «Оборот»; Период появляется, только если задана периодичность",
	"остаткииобороты": "измерения + ресурсы с суффиксами «НачальныйОстаток», «Приход», «Расход», «Оборот», «КонечныйОстаток»",
	"срезпоследних":   "измерения, ресурсы и реквизиты регистра сведений + Период (для периодического регистра)",
	"срезпервых":      "измерения, ресурсы и реквизиты регистра сведений + Период (для периодического регистра)",
}

func fieldsHint(table, kind string) string {
	// У небухгалтерских регистров состав свой — бухгалтерская таблица здесь не просто
	// бесполезна, она уводит.
	if kind != "" && kind != "регистрбухгалтерии" {
		if rule, ok := nonAccountingFields[strings.ToLower(table)]; ok {
			return fmt.Sprintf("поля виртуальной таблицы %s: %s. Точные имена — инструмент object по этому регистру", table, rule)
		}
		return ""
	}
	fields, ok := virtualTableFields[table]
	if !ok {
		return ""
	}
	return fmt.Sprintf("поля виртуальной таблицы %s: %s", table, strings.Join(fields, ", "))
}

// mainTableHas — поле принадлежит основной таблице регистра, а не виртуальной. Самый частый
// случай: Регистратор и СчетДт есть у самих движений, но не у их итогов.
var mainTableOnly = map[string]string{
	"Регистратор": "основная таблица РегистрБухгалтерии.Хозрасчетный (без виртуальной части)",
	"СчетДт":      "основная таблица движений либо виртуальная ОборотыДтКт",
	"СчетКт":      "основная таблица движений либо виртуальная ОборотыДтКт",
	"Сумма":       "основная таблица движений; в итоговых таблицах ресурс называется СуммаОборотДт/Кт и подобными",
	"Содержание":  "основная таблица движений",
	"Активность":  "основная таблица движений",
}

// ── Предупреждения о том, что платформа пропускает молча ──────────────────────
//
// Синтаксическую ошибку платформа назовёт сама. Опаснее конструкции, которые РАЗБИРАЮТСЯ
// и ВЫПОЛНЯЮТСЯ, а результат отдают неверный: отказа нет, пустая выборка неотличима от
// честного «данных нет», и число из неё попадает в отчёт. Такие места разбираются по тексту
// запроса и выдаются вместе с успешным разбором — предупреждением, а не отказом: запрос
// может быть и намеренным.

var (
	// Ссылка, сравненная со строковым литералом. Ноль строк, ошибки нет.
	reRefEqString = regexp.MustCompile(`(?i)\.(Ссылка|Ref)\s*(=|<>)\s*"`)
	// Остатки на дату без времени: движения этого дня в остаток не войдут.
	reBareDateBoundary = regexp.MustCompile(`(?i)\.(Остатки|ОстаткиИОбороты)\s*\(\s*ДАТАВРЕМЯ\s*\(\s*\d{4}\s*,\s*\d{1,2}\s*,\s*\d{1,2}\s*\)`)
)

// QuietTraps — предупреждения по тексту запроса. Пусто, если ловушек не видно.
func QuietTraps(query string) []string {
	var out []string
	if reRefEqString.MatchString(query) {
		out = append(out, "ссылка сравнивается со строкой — платформа не возражает, но совпадений не будет "+
			"НИКОГДА: сравнивайте с параметром-объектом или ЗНАЧЕНИЕ(Справочник.X.Имя). "+
			"Пустой ответ здесь неотличим от «в базе такого нет»")
	}
	if reBareDateBoundary.MatchString(query) {
		out = append(out, "остаток берётся на дату без времени, то есть на НАЧАЛО дня: движения этого дня "+
			"в него не войдут, и отчёт разойдётся с оборотами ровно на них. Для конца дня — "+
			"КОНЕЦПЕРИОДА(&Дата, ДЕНЬ)")
	}
	return out
}

// EnrichQueryRefusal дописывает к отказу подсказки, выведенные из текста ошибки и текста
// запроса. Отказ не заменяется и не смягчается: добавляются только строки Hints, а первая
// строка — «вызов не выполнен» — остаётся нетронутой.
func EnrichQueryRefusal(err error, query string, params map[string]any) error {
	e, ok := err.(*refusal.Error)
	if !ok || e.Kind != refusal.BaseError {
		return err
	}
	text := e.What + " " + e.Why
	table := virtualTableIn(query)
	kind := registerKindIn(query)
	var hints []string

	if m := reFieldNotFound.FindStringSubmatch(text); m != nil {
		f := m[1]
		// Про СчетДт/СчетКт/Содержание говорить осмысленно только для регистра бухгалтерии:
		// у товарного регистра таких полей нет ни в какой таблице.
		accounting := kind == "" || kind == "регистрбухгалтерии"
		if where, ok := mainTableOnly[f]; ok && table != "" && (accounting || f == "Регистратор") {
			if f == "Регистратор" && !accounting {
				where = "основная таблица движений регистра (без виртуальной части)"
			}
			hints = append(hints, fmt.Sprintf("поля %q нет у виртуальной таблицы %s — оно есть здесь: %s", f, table, where))
		}
		if h := fieldsHint(table, kind); h != "" {
			hints = append(hints, h)
		}
		hints = append(hints, "состав полей прикладного объекта отдаёт инструмент object — он читает эту базу, а не общее правило")
	}

	if m := reTableNotFound.FindStringSubmatch(text); m != nil {
		name := m[1]
		if strings.HasPrefix(name, "Справочник.ПланСчетов") {
			hints = append(hints, "планы счетов адресуются как ПланСчетов.<Имя>, без префикса Справочник")
		}
		hints = append(hints, "имена таблиц в единственном числе: Справочник.X, Документ.X, РегистрНакопления.X, "+
			"РегистрБухгалтерии.X, ПланСчетов.X; перечисления таблицами не являются")
		hints = append(hints, "перечень объектов категории отдаёт инструмент metadata")
	}

	if m := reBadParams.FindStringSubmatch(text); m != nil {
		name := m[1]
		if i := strings.LastIndex(name, "."); i >= 0 {
			name = name[i+1:]
		}
		// «Неверные параметры» приходит и на операторы, а не только на виртуальные таблицы:
		// платформа так отвечает, когда слева от оператора стоит не то, что он принимает.
		// Живой случай 26.08.2026: ГДЕ ПРЕДСТАВЛЕНИЕ ПОДОБНО "96%" — ПРЕДСТАВЛЕНИЕ это ФУНКЦИЯ
		// от поля, а не поле, и сравнивать её с шаблоном нельзя.
		if _, isTable := virtualTableSignature[name]; !isTable {
			if strings.Contains(strings.ToUpper(query), "ПРЕДСТАВЛЕНИЕ") {
				hints = append(hints,
					"ПРЕДСТАВЛЕНИЕ — функция от поля: ПРЕДСТАВЛЕНИЕ(Счет), а не имя колонки",
					`отбирать по представлению нельзя: берите реквизит — ГДЕ Код ПОДОБНО "96%" либо ГДЕ Наименование ПОДОБНО "%текст%"`)
			}
			hints = append(hints, fmt.Sprintf(
				"платформа отвергла %q: слева от оператора стоит выражение неподходящего типа — "+
					"сравнивайте поле того же типа, а строковый шаблон только со строкой", name))
		}
		if sig, ok := virtualTableSignature[name]; ok {
			hints = append(hints, "сигнатура: "+sig)
			if len(m) > 2 && m[2] != "" {
				hints = append(hints, fmt.Sprintf("платформа отвергла параметр №%s — сверьте позицию по сигнатуре: "+
					"пропущенный параметр обозначается пустым местом между запятыми", m[2]))
			}
		}
	}

	if m := reNoParamValue.FindStringSubmatch(text); m != nil {
		p := m[1]
		if len(params) == 0 {
			hints = append(hints, fmt.Sprintf("параметр &%s объявлен в тексте, но поле parameters пустое — "+
				`передайте {"%s": …}; даты строкой ГГГГ-ММ-ДД`, p, p))
		} else {
			keys := make([]string, 0, len(params))
			for k := range params {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			hints = append(hints, fmt.Sprintf("передано: %s — имя пишется без амперсанда и совпадает с текстом запроса посимвольно",
				strings.Join(keys, ", ")))
		}
	}

	if m := reSyntax.FindStringSubmatch(text); m != nil {
		word := strings.ToUpper(strings.TrimSpace(m[1]))
		if repl, ok := languageReplacements[word]; ok {
			hints = append(hints, fmt.Sprintf("конструкции %q в языке запросов нет — используйте %s", m[1], repl))
		}
		// Замена решает частый случай; полная страница нужна, когда случай не частый. Отсылаем
		// к справке ПЛАТФОРМЫ, а не к общему знанию: язык описан вендором для конкретного релиза.
		hints = append(hints, fmt.Sprintf(
			"полная страница языка запросов — справка платформы (раздел shquery): поиск по слову %q", m[1]))
	}

	if strings.Contains(text, "неограниченной длины") || strings.Contains(text, "несовместимых типов") {
		hints = append(hints,
			"ссылку нельзя сравнивать со строкой: либо сравнивайте с полем ссылочного типа, "+
				"либо через реквизит — Счет.Код = \"96\", Партнер.Наименование = &Имя",
			"строка на месте ссылки даёт не ошибку, а ПУСТОЙ результат — молча, поэтому такой отбор проверяют отдельно")
	}

	// Справка по слову, на котором споткнулась платформа. Это и есть охват: рукописный список
	// замен покрывает лишь то, что успели угадать, а справка — всё, что вендор описал. Слово
	// платформа называет сама, поэтому искать его не приходится.
	if word := failedWord(text); word != "" {
		if page := lookupSyntax(word); page != "" {
			hints = append(hints, page)
		}
	}

	if len(hints) == 0 {
		return err
	}
	// Возвращаем копию: отказ мог прийти из общего пути и попасть кому-то ещё.
	out := *e
	out.Hints = append(append([]string{}, e.Hints...), hints...)
	return &out
}

// failedWord — слово, на котором споткнулся разбор запроса. Платформа называет его в кавычках,
// и это лучший ключ к справке: он взят из первоисточника, а не угадан по тексту запроса.
func failedWord(text string) string {
	for _, re := range []*regexp.Regexp{reSyntax, reFieldNotFound, reTableNotFound} {
		if m := re.FindStringSubmatch(text); m != nil {
			w := strings.TrimSpace(m[1])
			// Составное имя вида Справочник.ПланСчетов.Хозрасчетный сокращаем до последней
			// части: в справке страница названа по объекту, а не по пути к нему.
			if i := strings.LastIndex(w, "."); i >= 0 && i < len(w)-1 {
				w = w[i+1:]
			}
			if len([]rune(w)) >= 3 {
				return w
			}
		}
	}
	return ""
}

// lookupSyntax — выдержка из справки платформы по слову. Молчит, когда справки нет или страница
// не нашлась: отказ обязан оставаться читаемым и без неё.
func lookupSyntax(word string) string {
	db, err := openKB()
	if err != nil {
		return ""
	}
	defer db.Close()

	var title, body string
	row := db.QueryRow(`SELECT title, text FROM pages
	                     WHERE config='platform' AND object = ? COLLATE NOCASE LIMIT 1`, word)
	if err := row.Scan(&title, &body); err != nil {
		row = db.QueryRow(`SELECT title, text FROM pages
		                    WHERE config='platform' AND title LIKE ? LIMIT 1`, "%"+word+"%")
		if err := row.Scan(&title, &body); err != nil {
			return ""
		}
	}
	body = strings.TrimSpace(body)
	if len(body) > 700 {
		body = body[:700] + "…"
	}
	return fmt.Sprintf("справка платформы, %s:%c%s%c(полностью — инструмент syntax, имя с префиксом вашего сервера)",
		strings.TrimSpace(title), '\n', body, '\n')
}
