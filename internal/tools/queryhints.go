// Обогащение отказов по запросу.
//
// Платформа отвечает на негодный запрос точно, но односложно: «Поле не найдено "Регистратор"».
// Для человека этого хватает — он знает, где смотреть; вызывающему инструмент приходится
// угадывать, и угадывает он плохо: замер 25.08.2026 показал, как после трёх таких отказов
// вызывающий бросает запросы и начинает считать числа вручную по общей выборке. Числа при этом
// получаются красивые и неверные.
//
// Поэтому к отказу дописывается то, что известно и без обращения к базе: состав полей
// виртуальных таблиц, сигнатуры их параметров, замены для конструкций, которых в языке запросов
// нет. Подсказка приходит в момент, когда вызывающий уперся, и не требует от него догадаться
// спросить справку.
//
// Здесь только знание ПЛАТФОРМЫ — то, что одинаково в любой конфигурации. Состав конкретного
// объекта отдаёт инструмент object, и подменять его этой таблицей нельзя: у прикладного
// объекта поля свои.

