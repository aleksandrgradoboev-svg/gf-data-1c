// inputAliases — русские имена ключей входа, принимаемые наравне с латинскими.
// «база» в алиасы НЕ входит: base обязателен в схеме и должен иметь одно написание —
// иначе required требует латинский ключ, а схема разрешает и русский, и вызов с «база»
// отвергается валидатором раньше, чем алиас успевает сработать.
var inputAliases = map[string]string{
	"источник": "from", "псевдоним": "alias",
	"параметрыТаблицы": "table_params", "поля": "select", "отбор": "where",
	"группировка": "group_by", "порядок": "order_by",
	"различные": "distinct", "первые": "top",
	"соединения": "joins", "итоги": "totals", "параметры": "params",
}

// UnmarshalJSON принимает вход и с латинскими ключами, и с русскими. Русские остаются
// рабочими намеренно: они разосланы в примерах и методиках, а модель, однажды написавшая
// «источник», должна получить запрос, а не отказ валидации.
func (in *QueryBuildInput) UnmarshalJSON(b []byte) error {
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(b, &raw); err != nil {
		return err
	}
	renameKeys(raw, inputAliases)
	// Одно условие строкой — то же, что список из одного элемента. Схема это разрешает
	// (см. queryBuildSchema), здесь строка разворачивается в список, чтобы дальше по коду
	// был один вид данных, а не два.
	for _, ключ := range []string{"where", "group_by", "order_by", "table_params"} {
		сырое, есть := raw[ключ]
		if !есть {
			continue
		}
		var строка string
		if json.Unmarshal(сырое, &строка) == nil {
			обёрнуто, err := json.Marshal([]string{строка})
			if err != nil {
				return err
			}
			raw[ключ] = обёрнуто
		}
	}
	normalized, err := json.Marshal(raw)
	if err != nil {
		return err
	}
	type plain QueryBuildInput
	var obj plain
	if err := json.Unmarshal(normalized, &obj); err != nil {
		return err
	}
	*in = QueryBuildInput(obj)
	return nil
}

