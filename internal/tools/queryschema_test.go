// Колонки «поля» приходят от модели и строкой, и объектом. Обе формы обязаны проходить
// схему ДО обработчика и раскладываться в одну структуру — иначе отказ валидации
// выглядит для модели как поломка инструмента, и она уходит писать текст руками.

func TestQueryBuildПоляСтрокойИОбъектом(t *testing.T) {
	raw := `{"base":"ut11","источник":"Справочник.Номенклатура",
		"поля":["Ссылка", {"поле":"Наименование","как":"Имя"}, {"функция":"КОЛИЧЕСТВО","поле":"Ссылка","как":"Всего"}]}`
	var in QueryBuildInput
	if err := json.Unmarshal([]byte(raw), &in); err != nil {
		t.Fatalf("разбор ввода: %v", err)
	}
	if len(in.Поля) != 3 {
		t.Fatalf("колонок %d, ждали 3", len(in.Поля))
	}
	if in.Поля[0].Поле != "Ссылка" || in.Поля[0].Как != "" {
		t.Errorf("строка не легла в «поле»: %+v", in.Поля[0])
	}
	if in.Поля[1].Поле != "Наименование" || in.Поля[1].Как != "Имя" {
		t.Errorf("объект разобран неверно: %+v", in.Поля[1])
	}
	if in.Поля[2].Функция != "КОЛИЧЕСТВО" {
		t.Errorf("агрегат потерян: %+v", in.Поля[2])
	}
}

func TestQueryBuildСхемаДопускаетСтроку(t *testing.T) {
	s := queryBuildSchema()
	// select теперь сам anyOf: [строка-с-JSON-массивом, массив] — лояльность к
	// стрингифицированным спискам (02.09.2026). Форму элементов проверяем во
	// второй ветви anyOf.
	свойство := s.Properties["select"]
	if len(свойство.AnyOf) != 2 || свойство.AnyOf[0].Type != "string" || свойство.AnyOf[1].Type != "array" {
		t.Fatalf("select должен быть anyOf [string, array], получено %+v", свойство.AnyOf)
	}
	items := свойство.AnyOf[1].Items
	if items == nil || len(items.AnyOf) != 2 {
		t.Fatalf("элемент «поля» должен быть anyOf из двух форм, получено %+v", items)
	}
	if items.AnyOf[0].Type != "string" || items.AnyOf[1].Type != "object" {
		t.Errorf("ждали [string, object], получено [%s, %s]", items.AnyOf[0].Type, items.AnyOf[1].Type)
	}
	// Схема должна резолвиться и пропускать строку — это то, что SDK делает до вызова.
	resolved, err := s.Resolve(nil)
	if err != nil {
		t.Fatalf("схема не резолвится: %v", err)
	}
	var doc any
	_ = json.Unmarshal([]byte(`{"base":"ut11","from":"Справочник.Номенклатура","select":["Ссылка",{"field":"Код"}]}`), &doc)
	if err := resolved.Validate(doc); err != nil {
		t.Errorf("строка в select отвергнута схемой: %v", err)
	}
	_ = json.Unmarshal([]byte(`{"base":"ut11","from":"Справочник.Номенклатура","select":[42]}`), &doc)
	if err := resolved.Validate(doc); err == nil {
		t.Errorf("число в select должно отвергаться схемой")
	}

	// Русские ключи схемой не объявлены (она обязана быть латинской — требование
	// Anthropic API), но и не запрещены: additionalProperties пропускает их до разбора.
	// Значит форму элемента у них проверяет уже UnmarshalJSON — и обязан проверять так же
	// строго, иначе «совместимость» означала бы «что угодно вместо колонки».
	var in QueryBuildInput
	if err := json.Unmarshal([]byte(`{"base":"ut11","источник":"Справочник.Номенклатура","поля":["Ссылка",{"поле":"Код"}]}`), &in); err != nil {
		t.Errorf("русская форма отвергнута разбором: %v", err)
	} else if len(in.Поля) != 2 || in.Поля[0].Поле != "Ссылка" || in.Поля[1].Поле != "Код" {
		t.Errorf("русская форма разобрана неверно: %+v", in.Поля)
	}
	if err := json.Unmarshal([]byte(`{"base":"ut11","источник":"Справочник.Номенклатура","поля":[42]}`), &in); err == nil {
		t.Errorf("число в «поля» должно отвергаться разбором")
	}
}

// Спор отбора с параметром виртуальной таблицы — случай, который платформа пропускает
// молча. Запрос верен синтаксически и возвращает ноль строк; ноль строк неотличим от
// «в базе пусто». Живой случай 31.08.2026 на bu3: accounts по счёту 51 давал обороты,
// собранный запрос по тому же счёту — пусто, четырьмя способами подряд.

func TestПолеУсловия(t *testing.T) {
	случаи := map[string]string{
		"Счет В ИЕРАРХИИ(&Счет)":           "Счет",
		"ОстаткиИОбороты.Счет = &Счет":     "Счет",
		"Обороты.Счет=&Счет":               "Счет",
		"Дата МЕЖДУ &Н И &К":               "Дата",
		"Склад В (&Склады)":                "Склад",
		"Номенклатура.Наименование = &Имя": "Наименование",
		"":                    "",
		"СУММА(Оборот) > 100": "", // не имя поля — проверка обязана молчать
	}
	for вход, ждём := range случаи {
		if got := полеУсловия(вход); got != ждём {
			t.Errorf("полеУсловия(%q) = %q, ждали %q", вход, got, ждём)
		}
	}
}

func TestСпорОтбораЛовитсяДоБазы(t *testing.T) {
	// Ровно тот вызов, что дал 0 строк на bu3.
	err := проверитьСпорОтбора("bu3",
		[]string{"&Н", "&К", "Месяц", "Счет В ИЕРАРХИИ(&Счет)"},
		[]string{"Счет = &Счет"})
	if err == nil {
		t.Fatal("спор отбора не пойман — запрос уйдёт в базу и вернёт ноль строк")
	}
	текст := err.Error()
	for _, кусок := range []string{"ОТКАЗ", "bu3", "Счет", "ноль строк", "accounts"} {
		if !strings.Contains(текст, кусок) {
			t.Errorf("в отказе нет %q; отказ целиком:\n%s", кусок, текст)
		}
	}
}

func TestСпорОтбораНеМешаетЗаконномуЗапросу(t *testing.T) {
	// Разные поля в параметрах и в отборе — законно и обязано проходить.
	if err := проверитьСпорОтбора("bu3",
		[]string{"&Н", "&К", "Месяц", "Счет В ИЕРАРХИИ(&Счет)"},
		[]string{"Организация = &Орг"}); err != nil {
		t.Errorf("законный запрос отвергнут: %v", err)
	}
	// Отбор без параметров таблицы.
	if err := проверитьСпорОтбора("bu3", nil, []string{"Счет = &Счет"}); err != nil {
		t.Errorf("отбор без параметров таблицы отвергнут: %v", err)
	}
	// Параметры без отбора.
	if err := проверитьСпорОтбора("bu3", []string{"&Н", "&К", "Счет В ИЕРАРХИИ(&Счет)"}, nil); err != nil {
		t.Errorf("параметры без отбора отвергнуты: %v", err)
	}
}

// Одно условие строкой вместо списка — самая частая форма у слабой модели. Схема обязана
// её принимать: сырой отказ валидатора («want one of null, array») не переведён на язык
// сервера, не говорит, как исправить, и читается моделью как поломка инструмента — после
// чего она уходит писать текст запроса руками, мимо построителя.

func TestСтрокаВместоСпискаПринимается(t *testing.T) {
	raw := `{"base":"bu3","from":"Документ.СписаниеСРасчетногоСчета","select":["Ссылка"],
		"where":"Дата МЕЖДУ &Н И &К","group_by":"Ссылка","order_by":"Ссылка",
		"table_params":"&Н"}`
	var in QueryBuildInput
	if err := json.Unmarshal([]byte(raw), &in); err != nil {
		t.Fatalf("строка в списочном поле отвергнута разбором: %v", err)
	}
	for имя, got := range map[string][]string{
		"where": in.Отбор, "group_by": in.Группировка,
		"order_by": in.Порядок, "table_params": in.ПараметрыТаблицы,
	} {
		if len(got) != 1 {
			t.Errorf("%s: получено %d элементов, ждали 1 (%v)", имя, len(got), got)
		}
	}
	if in.Отбор[0] != "Дата МЕЖДУ &Н И &К" {
		t.Errorf("условие исказилось: %q", in.Отбор[0])
	}
}

func TestСхемаПропускаетСтрокуВСписочныхПолях(t *testing.T) {
	resolved, err := queryBuildSchema().Resolve(nil)
	if err != nil {
		t.Fatalf("схема не резолвится: %v", err)
	}
	for _, док := range []string{
		`{"base":"bu3","from":"Справочник.Валюты","select":["Ссылка"],"where":"Код = 643"}`,
		`{"base":"bu3","from":"Справочник.Валюты","select":["Ссылка"],"where":["Код = 643"]}`,
		`{"base":"bu3","from":"Справочник.Валюты","select":["Ссылка"],"group_by":"Ссылка"}`,
		`{"base":"bu3","from":"Справочник.Валюты","select":["Ссылка"],"table_params":"&Н"}`,
	} {
		var v any
		_ = json.Unmarshal([]byte(док), &v)
		if err := resolved.Validate(v); err != nil {
			t.Errorf("схема отвергла законный вызов %s: %v", док, err)
		}
	}
	// Число списочным полем по-прежнему отвергается: послабление ровно на строку.
	var v any
	_ = json.Unmarshal([]byte(`{"base":"bu3","from":"Справочник.Валюты","select":["Ссылка"],"where":42}`), &v)
	if err := resolved.Validate(v); err == nil {
		t.Error("число в where должно отвергаться схемой")
	}
}
