package tools

import (
	"strings"
	"testing"
)

// Ссылка, сравненная со строкой, — запрос выполняется и всегда даёт ноль строк. Платформа
// молчит, пустой ответ неотличим от «в базе такого нет», и число из него уходит в отчёт.
// Проверено на живой базе: 0 строк против 1 у сравнения по наименованию.
func TestQuietTrapsСсылкаСоСтрокой(t *testing.T) {
	q := `ВЫБРАТЬ Н.Ссылка ИЗ Справочник.Номенклатура КАК Н ГДЕ Н.Ссылка = "Кабель"`
	traps := QuietTraps(q)
	if len(traps) == 0 {
		t.Fatal("сравнение ссылки со строкой не замечено")
	}
	if !strings.Contains(traps[0], "ссылка сравнивается со строкой") {
		t.Errorf("предупреждение не про то: %q", traps[0])
	}
}

// Остаток «на дату» берётся на начало дня: движения этой даты в него не входят. Проверено
// числами — 141 на 23.06 против 140 на 23.06 23:59:59 при движении −1 за этот день.
func TestQuietTrapsГраницаПериода(t *testing.T) {
	q := `ВЫБРАТЬ О.ВНаличииОстаток ИЗ РегистрНакопления.ТоварыНаСкладах.Остатки(ДАТАВРЕМЯ(2026,6,23), ) КАК О`
	if len(QuietTraps(q)) == 0 {
		t.Fatal("остаток на дату без времени не замечен")
	}
	// С временем — предупреждать не о чем, граница задана явно.
	ok := `ВЫБРАТЬ О.ВНаличииОстаток ИЗ РегистрНакопления.ТоварыНаСкладах.Остатки(ДАТАВРЕМЯ(2026,6,23,23,59,59), ) КАК О`
	if traps := QuietTraps(ok); len(traps) != 0 {
		t.Errorf("ложное предупреждение на явной границе: %q", traps)
	}
}

// Чистый запрос не должен обрастать предупреждениями: шум приучает их не читать.
func TestQuietTrapsМолчитНаЧистомЗапросе(t *testing.T) {
	q := `ВЫБРАТЬ Н.Наименование ИЗ Справочник.Номенклатура КАК Н ГДЕ Н.Наименование = "Кабель"`
	if traps := QuietTraps(q); len(traps) != 0 {
		t.Errorf("предупреждения на ровном месте: %q", traps)
	}
}

// Виртуальных таблиц с именем «Остатки» две разных — у регистра накопления и у регистра
// бухгалтерии, и состав полей у них не совпадает. До 26.08.2026 подсказка знала только
// бухгалтерскую и уверенно называла Счет и Субконто в ответе про товарный регистр.
func TestFieldsHintРазличаетВидРегистра(t *testing.T) {
	накопление := registerKindIn(`ИЗ РегистрНакопления.ТоварыНаСкладах.Остатки(&Д, ) КАК Ост`)
	if накопление != "регистрнакопления" {
		t.Fatalf("вид регистра определён как %q", накопление)
	}
	h := fieldsHint("Остатки", накопление)
	if strings.Contains(h, "Субконто") || strings.Contains(h, "Счет") {
		t.Errorf("товарному регистру подсказаны бухгалтерские поля: %q", h)
	}
	if !strings.Contains(h, "Остаток") {
		t.Errorf("не названо правило переименования ресурса: %q", h)
	}

	бухгалтерия := registerKindIn(`ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&Д, , , ) КАК Ост`)
	if бухгалтерия != "регистрбухгалтерии" {
		t.Fatalf("вид регистра определён как %q", бухгалтерия)
	}
	if h := fieldsHint("Остатки", бухгалтерия); !strings.Contains(h, "Субконто1") {
		t.Errorf("бухгалтерскому регистру не названы его поля: %q", h)
	}
}
